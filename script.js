let n1 = prompt('digite o primeiro numero:')
n1=Number(n1)
let n2 = prompt('digite o segundo numero:')
n2=Number(n2)

alert(`${n1} > ${n2} = ${n1 > n2}`)
alert(`${n1} >= ${n2} = ${n1 >+ n2}`)
alert(`${n1} < ${n2} = ${n1 < n2}`)
alert(`${n1} <= ${n2} = ${n1 <= n2}`)

alert(`${n1} == ${n2} = ${n1 == n2}`)
alert(`${n1} != ${n2} = ${n1 != n2}`)

alert(`${n1} === ${n2} = ${n1 == String(n2)}`)
alert(`${n1} !== ${n2} = ${n1 != String(n2)}`)